local function runUrl(url, label)
    if not url or url == "" then return false end

    -- إذا ما يبدأ بـ http → استخدم BASE_URL
    if not string.find(url, "^https?://") then
        url = BASE_URL .. url
    end

    local ok, err = pcall(function()
        local src = game:HttpGet(url)
        local fn, ce = loadstring(src)
        if not fn then error("Compile: "..tostring(ce)) end
        fn()
    end)
    if not ok then warn("[ZEMPAROE] "..tostring(label).." → "..tostring(err)); return false end
    return true
end

